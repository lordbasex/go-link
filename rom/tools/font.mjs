/** An 8x8 glyph as pens: ink, a dark shadow one pixel down-right, else transparent (15). */
export function glyphPixels(ch, ink = 1, shadow = 2) {
  const rows = GLYPHS[ch];
  const px = Array.from({ length: 8 }, () => new Array(8).fill(15));
  if (!rows) return px;
  rows.forEach((row, y) => {
    for (let x = 0; x < 5; x++) {
      if (row[x] !== "#") continue;
      if (px[y + 1 + 1]?.[x + 1 + 1] === 15) px[y + 1 + 1][x + 1 + 1] = shadow;
      px[y + 1][x + 1] = ink;
    }
  });
  return px;
}
